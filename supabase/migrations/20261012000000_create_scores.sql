create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(trim(nickname)) between 1 and 20),
  time integer not null check (time >= 0),
  created_at timestamptz not null default now()
);

alter table public.scores
add column if not exists created_at timestamptz not null default now();

alter table public.scores enable row level security;

drop policy if exists "Scores are publicly readable" on public.scores;
create policy "Scores are publicly readable"
on public.scores
for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can submit a valid score" on public.scores;
create policy "Anyone can submit a valid score"
on public.scores
for insert
to anon, authenticated
with check (
  time >= 0
  and char_length(trim(nickname)) between 1 and 20
);

create index if not exists scores_time_created_at_idx
on public.scores (time desc, created_at asc);
